# Route: Trigger NotificationAgent Scan and Fetch User Notifications
@agent_bp.route('/notifications', methods=['GET', 'POST'])
@login_required
def trigger_notifications():
    """Scans and retrieves notifications."""
    student_id = get_active_student_id()
    if not student_id:
        return jsonify({"error": "Forbidden", "message": "Valid student session required."}), 403
        
    manager = AgentManager(student_id)
    
    # Run scan to update database state
    manager.execute_agent("NotificationAgent")
    
    if request.method == 'GET':
        rows = execute_query(
            "SELECT id, title, message, type, is_read, created_at FROM notifications "
            "WHERE student_id = ? ORDER BY created_at DESC LIMIT 30;",
            (student_id,),
            fetch_all=True
        )
        return jsonify([dict(row) for row in rows]), 200
        
    elif request.method == 'POST':
        # Mark all as read
        execute_query(
            "UPDATE notifications SET is_read = 1 WHERE student_id = ? AND is_read = 0;",
            (student_id,),
            commit=True
        )
        return jsonify({"message": "All notifications marked as read."}), 200
