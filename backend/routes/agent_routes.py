from flask import Blueprint, request, jsonify
from flask_login import login_required, current_user
from backend.agents.agent_manager import AgentManager
from backend.database.connection import execute_query
from backend.middleware.security import rate_limit, sanitize_input
from backend.middleware.logger import log_activity

agent_bp = Blueprint('agents', __name__)

def get_active_student_id():
    """Helper to verify current user is a student and return student_id, or validate student_id for Admin."""
    if not current_user.is_authenticated:
        return None
    if current_user.role == 'Student':
        return current_user.student_id
    if current_user.role == 'Admin':
        raw_id = request.args.get("student_id") or (request.json.get("student_id") if request.is_json else None)
        if raw_id:
            try:
                sid = int(raw_id)
                row = execute_query("SELECT id FROM students WHERE id = ?;", (sid,), fetch_one=True)
                if row:
                    return row['id']
            except (ValueError, TypeError):
                pass
        return None
    return None

# Route: Trigger PlannerAgent
@agent_bp.route('/planner', methods=['GET', 'POST'])
@login_required
def trigger_planner():
    """Triggers the PlannerAgent to calculate study plan slots."""
    student_id = get_active_student_id()
    if not student_id:
        return jsonify({"error": "Forbidden", "message": "Valid student session required."}), 403
        
    manager = AgentManager(student_id)
    payload = request.get_json() if request.is_json else {}
    plan_data = manager.execute_agent("PlannerAgent", payload)
    return jsonify(plan_data), 200

# Route: Save Study Plan generated by PlannerAgent
@agent_bp.route('/planner/save', methods=['POST'])
@login_required
def save_planner_slots():
    """Saves generated study plan slots to the database."""
    student_id = get_active_student_id()
    if not student_id:
        return jsonify({"error": "Forbidden", "message": "Valid student session required."}), 403
        
    data = request.get_json() or {}
    slots = data.get("slots", [])
    
    from backend.services.planner_service import save_study_slots
    from backend.services.exceptions import AppError
    try:
        saved_count = save_study_slots(student_id, slots)
        log_activity(current_user.id, "SAVE_STUDY_PLAN", f"Saved {saved_count} study slots.", request.remote_addr)
        return jsonify({
            "message": f"Successfully scheduled and persisted {saved_count} study sessions.",
            "saved_count": saved_count
        }), 201
    except AppError as e:
        return jsonify(e.to_dict()), e.status_code

