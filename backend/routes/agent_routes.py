from flask import Blueprint, request, jsonify
from flask_login import login_required, current_user
from backend.agents.agent_manager import AgentManager
from backend.database.connection import execute_query
from backend.middleware.security import rate_limit, sanitize_input
from backend.middleware.logger import log_activity

agent_bp = Blueprint('agents', __name__)

def get_active_student_id():
    """Helper to verify current user is a student and return student_id."""
    if not current_user.is_authenticated:
        return None
    if current_user.role == 'Student':
        return current_user.student_id
    # If admin, read parameter or default
    return request.args.get("student_id") or request.json.get("student_id") if request.is_json else None

# Route: Trigger PlannerAgent
@agent_bp.route('/planner', methods=['GET', 'POST'])
@login_required
def trigger_planner():
    """Triggers the PlannerAgent to calculate study plan slots."""
    student_id = get_active_student_id()
    if not student_id:
        return jsonify({"error": "Forbidden", "message": "Valid student session required."}), 403
        
    manager = AgentManager(student_id)
    payload = request.get_json() if request.is_json else {}
    plan_data = manager.execute_agent("PlannerAgent", payload)
    return jsonify(plan_data), 200

